// Generate from the actual migrated local PostgreSQL schema; never needs cloud secrets.
import { format, resolveConfig } from "prettier";
import { schemaDatabase } from "../tests/backend/database.mjs";
import { readFile, writeFile } from "node:fs/promises";
const db = await schemaDatabase();
const file = new URL("../src/integrations/supabase/types.ts", import.meta.url);
try {
  const map = (t) =>
    t.endsWith("[]")
      ? `${map(t.slice(0, -2))}[]`
      : ({
          uuid: "string",
          text: "string",
          boolean: "boolean",
          integer: "number",
          bigint: "number",
          numeric: "number",
          "timestamp with time zone": "string",
          date: "string",
          json: "Json",
          jsonb: "Json",
          void: "undefined",
          app_role: '"admin" | "caller"',
        }[t] ?? "unknown");
  const tables = {};
  for (const { table_name: name } of (
    await db.query(
      "select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' order by table_name",
    )
  ).rows) {
    const cols = (
      await db.query(
        `select a.attname name,format_type(a.atttypid,null) type,not a.attnotnull nullable,d.oid is not null has_default from pg_attribute a join pg_class c on c.oid=a.attrelid join pg_namespace n on n.oid=c.relnamespace left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum where n.nspname='public' and c.relname=$1 and a.attnum>0 and not a.attisdropped order by a.attnum`,
        [name],
      )
    ).rows;
    const rels = (
      await db.query(
        `select c.conname name,fr.relname target,array(select a.attname from unnest(c.conkey) with ordinality k(num,ord) join pg_attribute a on a.attrelid=c.conrelid and a.attnum=k.num order by k.ord) cols,array(select a.attname from unnest(c.confkey) with ordinality k(num,ord) join pg_attribute a on a.attrelid=c.confrelid and a.attnum=k.num order by k.ord) refs from pg_constraint c join pg_class t on t.oid=c.conrelid join pg_namespace n on n.oid=t.relnamespace join pg_class fr on fr.oid=c.confrelid join pg_namespace fn on fn.oid=fr.relnamespace where c.contype='f' and n.nspname='public' and fn.nspname='public' and t.relname=$1`,
        [name],
      )
    ).rows;
    tables[name] =
      `{\n${["Row", "Insert", "Update"].map((mode) => `${mode}: {\n${cols.map((c) => `${JSON.stringify(c.name)}${mode === "Update" || (mode === "Insert" && (c.has_default || c.nullable)) ? "?" : ""}: ${map(c.type)}${c.nullable ? " | null" : ""}`).join("\n")}\n}`).join("\n")}\nRelationships: [${rels.map((r) => `{foreignKeyName:${JSON.stringify(r.name)}; columns:${JSON.stringify(r.cols)}; isOneToOne:false; referencedRelation:${JSON.stringify(r.target)}; referencedColumns:${JSON.stringify(r.refs)}}`).join(",")}]\n}`;
  }
  const functions = (
    await db.query(
      `select p.proname name,p.proargnames names,p.pronargdefaults defaults,pg_catalog.format_type(p.prorettype,null) result,array(select pg_catalog.format_type(t,null) from unnest(p.proargtypes::oid[]) t) types from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prorettype<>'trigger'::regtype order by p.proname`,
    )
  ).rows;
  const funcs = functions
    .map(
      (f) =>
        `${JSON.stringify(f.name)}: { Args: ${f.types.length ? "{" + f.types.map((t, i) => `${JSON.stringify(f.names[i])}${i >= f.types.length - f.defaults ? "?" : ""}: ${map(t)} | null`).join(";") + "}" : "Record<PropertyKey, never>"}; Returns: ${map(f.result)} }`,
    )
    .join("\n");
  const old = await readFile(file, "utf8");
  const tail = old.slice(old.indexOf("type DatabaseWithoutInternals"));
  const raw = `// Generated by npm run types:backend from the migrated Lovable Cloud schema.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]\nexport type Database = { __InternalSupabase: { PostgrestVersion: "14.18" }; public: { Tables: {\n${Object.entries(
    tables,
  )
    .map(([k, v]) => JSON.stringify(k) + ": " + v)
    .join(
      "\n",
    )}\n}; Views: { [_ in never]: never }; Functions: {\n${funcs}\n}; Enums: { app_role: "admin" | "caller" }; CompositeTypes: { [_ in never]: never } } }\n\n${tail}`;
  const output = await format(raw, {
    ...(await resolveConfig(file.pathname)),
    parser: "typescript",
  });
  if (process.argv.includes("--check")) {
    if (old !== output) throw new Error("Generated backend types are stale");
  } else await writeFile(file, output);
} finally {
  await db.close();
}
