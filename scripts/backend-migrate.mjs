/** One explicit, checksummed migration path. No automatic reset/adoption of existing databases. */
import postgres from "postgres";
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
const directory = new URL("../drizzle/migrations/", import.meta.url);
const migrations = [];
for (const name of (await readdir(directory)).filter((n) => /^\d{4}_.+\.sql$/.test(n)).sort()) {
  const sql = await readFile(new URL(name, directory), "utf8");
  migrations.push({ name, sql, hash: createHash("sha256").update(sql).digest("hex") });
}
const ledger = `CREATE SCHEMA IF NOT EXISTS backend_migrations;
REVOKE ALL ON SCHEMA backend_migrations FROM PUBLIC,anon,authenticated;
CREATE TABLE IF NOT EXISTS backend_migrations.applied(name text PRIMARY KEY,sha256 text NOT NULL,applied_at timestamptz NOT NULL DEFAULT now());`;
if (process.argv.includes("--bundle")) {
  const body =
    `-- GENERATED by npm run backend:bundle. Fresh Lovable Cloud business database only.\n-- Keeps the managed auth schema; aborts if business tables already exist.\nBEGIN;\nSELECT pg_advisory_xact_lock(71923103);\nDO $$ BEGIN IF to_regclass('public.profiles') IS NOT NULL THEN RAISE EXCEPTION 'Existing business schema: use verified migrations, never reset'; END IF; END $$;\n${ledger}\n` +
    migrations
      .map(
        (m) =>
          `${m.sql}\nINSERT INTO backend_migrations.applied(name,sha256) VALUES('${m.name}','${m.hash}');`,
      )
      .join("\n") +
    "\nCOMMIT;\n";
  const target = new URL("../backend/bootstrap.sql", import.meta.url);
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== body) throw new Error("bootstrap.sql is stale");
  } else await writeFile(target, body);
  console.log("Fresh-database bootstrap bundle verified.");
} else {
  if (!process.env.LOVABLE_DB_MIGRATION_URL)
    throw new Error(
      "LOVABLE_DB_MIGRATION_URL is required; use the secure Lovable runtime binding.",
    );
  const localTest = process.argv.includes("--local-test");
  if (
    localTest &&
    !["127.0.0.1", "localhost"].includes(new URL(process.env.LOVABLE_DB_MIGRATION_URL).hostname)
  )
    throw new Error("--local-test is restricted to a disposable localhost database");
  const sql = postgres(process.env.LOVABLE_DB_MIGRATION_URL, {
    max: 1,
    ssl: localTest ? false : { rejectUnauthorized: true },
    onnotice: () => {},
  });
  try {
    await sql.begin(async (tx) => {
      await tx`SELECT pg_advisory_xact_lock(71923103)`;
      const [state] =
        await tx`SELECT to_regclass('backend_migrations.applied') IS NOT NULL tracked,to_regclass('public.profiles') IS NOT NULL existing`;
      if (!state.tracked && state.existing)
        throw new Error(
          "Existing untracked schema: compare deployed migrations before adopting. No changes applied.",
        );
      const applied = state.tracked
        ? await tx`SELECT name,sha256 FROM backend_migrations.applied ORDER BY name`
        : [];
      for (let i = 0; i < applied.length; i++)
        if (applied[i].name !== migrations[i]?.name || applied[i].sha256 !== migrations[i]?.hash)
          throw new Error("Migration history/checksum mismatch. No changes applied.");
      const pending = migrations.slice(applied.length);
      console.log(
        "Pending migrations:",
        pending.map((m) => m.name),
      );
      if (!process.argv.includes("--apply")) return;
      await tx.unsafe(ledger);
      for (const m of pending) {
        await tx.unsafe(m.sql);
        await tx`INSERT INTO backend_migrations.applied(name,sha256) VALUES(${m.name},${m.hash})`;
      }
    });
  } finally {
    await sql.end();
  }
}
